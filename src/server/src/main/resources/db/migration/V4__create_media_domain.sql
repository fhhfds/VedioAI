  CONSTRAINT `fk_part_asset` FOREIGN KEY (`file_asset_id`) REFERENCES `file_asset` (`id`) ON DELETE RESTRICT ON UPDATE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='已确认分片';

CREATE TABLE `media` (
  `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '内部自增主键，不返回浏览器',
  `media_uid` VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT 'API中的mediaId',
  `owner_id` VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '服务端CurrentActor的主体ID；禁止客户端指定',
  `source_upload_session_id` BIGINT UNSIGNED NOT NULL COMMENT '来源会话；一个会话只创建一个素材',
  `file_asset_id` BIGINT UNSIGNED NULL DEFAULT NULL COMMENT '已通过校验的完整ORIGINAL文件',
  `display_name` VARCHAR(255) NOT NULL COMMENT '素材列表展示名称',
  `original_name` VARCHAR(255) NOT NULL COMMENT '原始来源名称',
  `size_bytes` BIGINT UNSIGNED NOT NULL COMMENT '总字节；完成时再次和实际字节核对',
  `duration_ms` BIGINT UNSIGNED NULL DEFAULT NULL COMMENT '实际视频时长，未知为NULL',
  `container_format` VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin NULL DEFAULT NULL COMMENT 'API container，对应真实容器',
  `video_codec` VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin NULL DEFAULT NULL COMMENT '实际视频编码',
  `audio_codec` VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin NULL DEFAULT NULL COMMENT '实际音频编码；无音轨允许NULL',
  `width` INT UNSIGNED NULL DEFAULT NULL COMMENT '探测到的宽度，像素',
  `height` INT UNSIGNED NULL DEFAULT NULL COMMENT '探测到的高度，像素',
  `status` VARCHAR(24) CHARACTER SET ascii COLLATE ascii_bin NOT NULL DEFAULT 'PROBE_PENDING' COMMENT 'PROBE_PENDING/READY/FAILED/DELETED',
  `version` BIGINT UNSIGNED NOT NULL DEFAULT 1 COMMENT 'API version，编辑/删除/处理提交的并发依据',
  `failure_code` VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL DEFAULT NULL COMMENT '公开失败原因码',
  `failure_message` VARCHAR(512) NULL DEFAULT NULL COMMENT '公开脱敏原因',
  `deleted_at` DATETIME(3) NULL DEFAULT NULL COMMENT '逻辑删除时间；不等于物理回收完成',
  `tombstone_retain_until` DATETIME(3) NULL DEFAULT NULL COMMENT '删除回执最短保留边界',
  `created_at` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) COMMENT '记录创建时间，UTC',
  `updated_at` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3) COMMENT '最后修改时间，UTC',
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_media_uid` (`media_uid`),
  UNIQUE KEY `uk_media_upload` (`source_upload_session_id`),
  KEY `ix_media_asset` (`file_asset_id`, `status`),
  KEY `ix_media_owner_created` (`owner_id`, `deleted_at`, `created_at` DESC, `media_uid` DESC),
  KEY `ix_media_owner_state` (`owner_id`, `deleted_at`, `status`, `created_at` DESC, `media_uid` DESC),
  KEY `ix_media_owner_name` (`owner_id`, `deleted_at`, `display_name`, `media_uid`),
  CONSTRAINT `fk_media_upload` FOREIGN KEY (`source_upload_session_id`) REFERENCES `upload_session` (`id`) ON DELETE RESTRICT ON UPDATE RESTRICT,
  CONSTRAINT `fk_media_asset` FOREIGN KEY (`file_asset_id`) REFERENCES `file_asset` (`id`) ON DELETE RESTRICT ON UPDATE RESTRICT,
  CONSTRAINT `ck_media_state` CHECK (`status` IN ('PROBE_PENDING','READY','FAILED','DELETED')),
  CONSTRAINT `ck_media_deleted` CHECK ((`status` = 'DELETED' AND `deleted_at` IS NOT NULL) OR (`status` <> 'DELETED' AND `deleted_at` IS NULL)),
  CONSTRAINT `ck_media_ready` CHECK (`status` <> 'READY' OR (`duration_ms` IS NOT NULL AND `container_format` IS NOT NULL AND `video_codec` IS NOT NULL)),
  CONSTRAINT `ck_media_size` CHECK (`size_bytes` > 0 AND `version` > 0),
  CONSTRAINT `ck_media_dimensions` CHECK ((`width` IS NULL OR `width` > 0) AND (`height` IS NULL OR `height` > 0))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='用户素材';

CREATE TABLE `job` (
  `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '内部自增主键，不返回浏览器',
  `job_uid` VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT 'API中的jobId',
  `owner_id` VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '服务端CurrentActor的主体ID；禁止客户端指定',
  `media_id` BIGINT UNSIGNED NOT NULL COMMENT '关联素材内部ID',
  `job_type` VARCHAR(24) CHARACTER SET ascii COLLATE ascii_bin NOT NULL DEFAULT 'MEDIA_INGEST' COMMENT '本板块固定MEDIA_INGEST',
  `status` VARCHAR(24) CHARACTER SET ascii COLLATE ascii_bin NOT NULL DEFAULT 'QUEUED' COMMENT 'QUEUED/RUNNING/SUCCEEDED/FAILED',
  `stage` VARCHAR(24) CHARACTER SET ascii COLLATE ascii_bin NOT NULL DEFAULT 'QUEUED' COMMENT 'QUEUED/ASSEMBLING/VALIDATING/PROBING/DONE/FAILED',
  `input_media_version` BIGINT UNSIGNED NOT NULL COMMENT '处理所依据的Media版本；防止迟到提交',
  `progress_percent` TINYINT UNSIGNED NULL DEFAULT NULL COMMENT '有可靠分母才设置，否则NULL',
  `attempt_no` INT UNSIGNED NOT NULL DEFAULT 0 COMMENT '每次领取执行递增',
  `max_attempts` SMALLINT UNSIGNED NOT NULL DEFAULT 3 COMMENT '基础设施恢复的有限次数建议，不对业务校验失败盲重试',
  `execution_id` VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NULL DEFAULT NULL COMMENT '当前这次执行的随机身份',
  `fence_token` BIGINT UNSIGNED NOT NULL DEFAULT 0 COMMENT '每次领取递增的执行代次',
  `lease_owner` VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NULL DEFAULT NULL COMMENT 'Worker实例标识',
  `lease_until` DATETIME(3) NULL DEFAULT NULL COMMENT '数据库时间计算的执行租约期限',
  `heartbeat_at` DATETIME(3) NULL DEFAULT NULL COMMENT '最近有效心跳',
  `available_at` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) COMMENT '可再次领取的最早时间',
  `started_at` DATETIME(3) NULL DEFAULT NULL COMMENT '首次执行时间',
  `finished_at` DATETIME(3) NULL DEFAULT NULL COMMENT '进入任务终态时间',
  `failure_code` VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL DEFAULT NULL COMMENT '错误分类',
  `failure_message` VARCHAR(512) NULL DEFAULT NULL COMMENT '脱敏错误说明',
  `created_at` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) COMMENT '记录创建时间，UTC',
  `updated_at` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3) COMMENT '最后修改时间，UTC',
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_job_uid` (`job_uid`),
  UNIQUE KEY `uk_job_media_type` (`media_id`, `job_type`),
  KEY `ix_job_claim` (`status`, `available_at`, `id`),
  KEY `ix_job_lease` (`status`, `lease_until`, `id`),
  CONSTRAINT `fk_job_media` FOREIGN KEY (`media_id`) REFERENCES `media` (`id`) ON DELETE RESTRICT ON UPDATE RESTRICT,
  CONSTRAINT `ck_job_type` CHECK (`job_type` = 'MEDIA_INGEST'),
  CONSTRAINT `ck_job_state` CHECK (`status` IN ('QUEUED','RUNNING','SUCCEEDED','FAILED')),
  CONSTRAINT `ck_job_stage` CHECK (`stage` IN ('QUEUED','ASSEMBLING','VALIDATING','PROBING','DONE','FAILED')),
  CONSTRAINT `ck_job_progress` CHECK (`progress_percent` IS NULL OR `progress_percent` <= 100),
  CONSTRAINT `ck_job_attempt` CHECK (`max_attempts` > 0 AND `input_media_version` > 0),
  CONSTRAINT `ck_job_running` CHECK (`status` <> 'RUNNING' OR (`execution_id` IS NOT NULL AND `lease_owner` IS NOT NULL AND `lease_until` IS NOT NULL))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='素材处理任务';

CREATE TABLE `idempotency_record` (
  `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '内部自增主键，不返回浏览器',
  `owner_id` VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '服务端CurrentActor的主体ID；禁止客户端指定',
  `operation` VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '首版固定UPLOAD_INIT',
  `idempotency_key` VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '客户端Idempotency-Key，16～128个允许的ASCII字符',
  `request_sha256` BINARY(32) NOT NULL COMMENT '服务端按规范化filename/size/contentType计算的请求摘要',
  `upload_session_id` BIGINT UNSIGNED NOT NULL COMMENT '同一次意图创建的会话',
  `expires_at` DATETIME(3) NOT NULL COMMENT '最短保留到期；活动/恢复窗口内不得清除',
  `created_at` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) COMMENT '记录创建时间，UTC',
  `updated_at` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3) COMMENT '最后修改时间，UTC',
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_idem_scope` (`owner_id`, `operation`, `idempotency_key`),
  KEY `ix_idem_upload` (`upload_session_id`),
  KEY `ix_idem_expire` (`expires_at`, `id`),
  CONSTRAINT `fk_idem_upload` FOREIGN KEY (`upload_session_id`) REFERENCES `upload_session` (`id`) ON DELETE RESTRICT ON UPDATE RESTRICT,
  CONSTRAINT `ck_idem_operation` CHECK (`operation` = 'UPLOAD_INIT'),
  CONSTRAINT `ck_idem_length` CHECK (CHAR_LENGTH(`idempotency_key`) BETWEEN 16 AND 128)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='初始化幂等记录';

CREATE TABLE `cleanup_record` (
  `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '内部自增主键，不返回浏览器',
  `file_asset_id` BIGINT UNSIGNED NOT NULL COMMENT '目标私有文件；也可定位该记录的staging_key',
  `reason` VARCHAR(24) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT 'ORPHAN/CANCELLED/EXPIRED/INGEST_FAILED/MEDIA_DELETED/PARTS_CONSUMED',
  `status` VARCHAR(24) CHARACTER SET ascii COLLATE ascii_bin NOT NULL DEFAULT 'PENDING' COMMENT 'PENDING/RUNNING/SUCCEEDED/FAILED',
  `attempt_no` INT UNSIGNED NOT NULL DEFAULT 0 COMMENT '实际文件删除尝试次数；仅等待引用释放不递增',
  `max_attempts` SMALLINT UNSIGNED NOT NULL DEFAULT 8 COMMENT '达到次数后保留失败，等待处理',
  `next_run_at` DATETIME(3) NULL DEFAULT CURRENT_TIMESTAMP(3) COMMENT '下次可领取时间；无自动重试时NULL',
  `execution_id` VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NULL DEFAULT NULL COMMENT '本次清理执行身份',
  `fence_token` BIGINT UNSIGNED NOT NULL DEFAULT 0 COMMENT '清理领取代次',
  `lease_owner` VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NULL DEFAULT NULL COMMENT '清理器实例',
  `lease_until` DATETIME(3) NULL DEFAULT NULL COMMENT '清理租约到期',
  `last_error_code` VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL DEFAULT NULL COMMENT '最近失败分类',
  `last_error_message` VARCHAR(512) NULL DEFAULT NULL COMMENT '脱敏清理错误',
  `finished_at` DATETIME(3) NULL DEFAULT NULL COMMENT '成功确认或最后终止时间',
  `created_at` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) COMMENT '记录创建时间，UTC',
  `updated_at` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3) COMMENT '最后修改时间，UTC',
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_cleanup_asset` (`file_asset_id`),
  KEY `ix_cleanup_claim` (`status`, `next_run_at`, `id`),
  KEY `ix_cleanup_lease` (`status`, `lease_until`, `id`),
  CONSTRAINT `fk_cleanup_asset` FOREIGN KEY (`file_asset_id`) REFERENCES `file_asset` (`id`) ON DELETE RESTRICT ON UPDATE RESTRICT,
  CONSTRAINT `ck_cleanup_state` CHECK (`status` IN ('PENDING','RUNNING','SUCCEEDED','FAILED')),
  CONSTRAINT `ck_cleanup_reason` CHECK (`reason` IN ('ORPHAN','CANCELLED','EXPIRED','INGEST_FAILED','MEDIA_DELETED','PARTS_CONSUMED')),
  CONSTRAINT `ck_cleanup_attempt` CHECK (`max_attempts` > 0),
  CONSTRAINT `ck_cleanup_running` CHECK (`status` <> 'RUNNING' OR (`execution_id` IS NOT NULL AND `lease_owner` IS NOT NULL AND `lease_until` IS NOT NULL))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='可靠文件清理记录';
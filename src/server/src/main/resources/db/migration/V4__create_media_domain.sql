-- VedioAI media domain V4: 8 tables for private media, uploads and ingest jobs.
-- Owner ids come from auth_user.user_uid; this schema does not seed users or media.

CREATE TABLE `owner_media_guard` (
  `owner_id` VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '当前主体ID，亦是本表主键',
  `created_at` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) COMMENT '记录创建时间，UTC',
  `updated_at` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3) COMMENT '最后修改时间，UTC',
  PRIMARY KEY (`owner_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='主体素材资源锁';

CREATE TABLE `upload_session` (
  `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '内部自增主键，不返回浏览器',
  `upload_uid` VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT 'API中的uploadId',
  `owner_id` VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '服务端CurrentActor的主体ID；禁止客户端指定',
  `original_name` VARCHAR(255) NOT NULL COMMENT '校验后的来源文件名；不作为文件系统路径',
  `declared_content_type` VARCHAR(100) NOT NULL COMMENT '客户端声明的MIME，仅供初筛',
  `expected_size_bytes` BIGINT UNSIGNED NOT NULL COMMENT '声明总字节，最终实际字节必须一致',
  `chunk_size_bytes` INT UNSIGNED NOT NULL COMMENT '接受该会话时确定的分片字节数',
  `total_parts` INT UNSIGNED NOT NULL COMMENT '服务端由大小与分片尺寸计算',
  `received_part_count` INT UNSIGNED NOT NULL DEFAULT 0 COMMENT '已确认唯一分片数；事务内更新的摘要',
  `received_bytes` BIGINT UNSIGNED NOT NULL DEFAULT 0 COMMENT '已确认唯一片字节和；不是浏览器上传进度',
  `policy_version` VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '策略版本',
  `policy_snapshot` JSON NOT NULL COMMENT '接受时的大小/时长/类型/分片等约束快照',
  `status` VARCHAR(24) CHARACTER SET ascii COLLATE ascii_bin NOT NULL DEFAULT 'CREATED' COMMENT 'CREATED/UPLOADING/COMPLETING/COMPLETED/FAILED/CANCELLED/EXPIRED',
  `version` BIGINT UNSIGNED NOT NULL DEFAULT 1 COMMENT '会话状态/摘要的条件更新版本',
  `expires_at` DATETIME(3) NOT NULL COMMENT '未完成提交会话的固定到期时间',
  `terminal_at` DATETIME(3) NULL DEFAULT NULL COMMENT '进入终态的时间',
  `receipt_retain_until` DATETIME(3) NULL DEFAULT NULL COMMENT '终态回执最短保留到何时；活动会话不得按此清除',
  `failure_code` VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL DEFAULT NULL COMMENT '安全的公开原因分类',
  `failure_message` VARCHAR(512) NULL DEFAULT NULL COMMENT '脱敏原因，不含私有路径/堆栈',
  `created_at` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) COMMENT '记录创建时间，UTC',
  `updated_at` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3) COMMENT '最后修改时间，UTC',
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_upload_uid` (`upload_uid`),
  KEY `ix_upload_owner_active` (`owner_id`, `status`, `id`),
  KEY `ix_upload_expire` (`status`, `expires_at`, `id`),
  KEY `ix_upload_receipt` (`receipt_retain_until`, `id`),
  CONSTRAINT `fk_upload_guard` FOREIGN KEY (`owner_id`) REFERENCES `owner_media_guard` (`owner_id`) ON DELETE RESTRICT ON UPDATE RESTRICT,
  CONSTRAINT `ck_upload_state` CHECK (`status` IN ('CREATED','UPLOADING','COMPLETING','COMPLETED','FAILED','CANCELLED','EXPIRED')),
  CONSTRAINT `ck_upload_parts` CHECK (`expected_size_bytes` > 0 AND `chunk_size_bytes` > 0 AND `total_parts` > 0 AND `total_parts` = ((`expected_size_bytes` + `chunk_size_bytes` - 1) DIV `chunk_size_bytes`)),
  CONSTRAINT `ck_upload_received` CHECK (`received_part_count` <= `total_parts` AND `received_bytes` <= `expected_size_bytes`),
  CONSTRAINT `ck_upload_version` CHECK (`version` > 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='上传会话';

CREATE TABLE `file_asset` (
  `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '内部自增主键，不返回浏览器',
  `owner_id` VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '服务端CurrentActor的主体ID；禁止客户端指定',
  `upload_session_id` BIGINT UNSIGNED NOT NULL COMMENT '来源上传会话',
  `asset_kind` VARCHAR(24) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT 'PART或ORIGINAL；首版不预建各种AI产物',
  `storage_profile` VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '服务端存储配置别名，不包含密码/Key',
  `object_key` VARCHAR(512) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '服务端生成的相对私有key；每次写入独立，不重复使用',
  `staging_key` VARCHAR(512) CHARACTER SET ascii COLLATE ascii_bin NULL DEFAULT NULL COMMENT '本次写入的临时key，供清理定位',
  `expected_size_bytes` BIGINT UNSIGNED NOT NULL COMMENT '该片/原文件预期字节',
  `actual_size_bytes` BIGINT UNSIGNED NULL DEFAULT NULL COMMENT '完成写入后由服务端得到的实际字节',
  `sha256` BINARY(32) NULL DEFAULT NULL COMMENT '服务端计算的SHA-256，数据库保存32字节',
  `status` VARCHAR(24) CHARACTER SET ascii COLLATE ascii_bin NOT NULL DEFAULT 'WRITING' COMMENT 'WRITING/STORED/REFERENCED/DELETE_PENDING/DELETED/FAILED',
  `write_token` VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '本次写入身份；分片HTTP或Worker execution身份',
  `write_lease_until` DATETIME(3) NULL DEFAULT NULL COMMENT '写入活性核对期限；过期不等于写者已停止',
  `version` BIGINT UNSIGNED NOT NULL DEFAULT 1 COMMENT '文件生命周期条件更新版本',
  `stored_at` DATETIME(3) NULL DEFAULT NULL COMMENT '私有对象完整发布并验证的时间',
  `deleted_at` DATETIME(3) NULL DEFAULT NULL COMMENT '确认物理对象/临时对象已回收的时间',
  `created_at` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) COMMENT '记录创建时间，UTC',
  `updated_at` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3) COMMENT '最后修改时间，UTC',
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_asset_storage` (`storage_profile`, `object_key`),
  KEY `ix_asset_upload` (`upload_session_id`, `asset_kind`, `status`, `id`),
  KEY `ix_asset_writing` (`status`, `write_lease_until`, `id`),
  CONSTRAINT `fk_asset_upload` FOREIGN KEY (`upload_session_id`) REFERENCES `upload_session` (`id`) ON DELETE RESTRICT ON UPDATE RESTRICT,
  CONSTRAINT `ck_asset_kind` CHECK (`asset_kind` IN ('PART','ORIGINAL')),
  CONSTRAINT `ck_asset_state` CHECK (`status` IN ('WRITING','STORED','REFERENCED','DELETE_PENDING','DELETED','FAILED')),
  CONSTRAINT `ck_asset_expected` CHECK (`expected_size_bytes` > 0),
  CONSTRAINT `ck_asset_stored` CHECK (`status` NOT IN ('STORED','REFERENCED') OR (`actual_size_bytes` IS NOT NULL AND `actual_size_bytes` = `expected_size_bytes` AND `sha256` IS NOT NULL)),
  CONSTRAINT `ck_asset_version` CHECK (`version` > 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='私有文件资产';

CREATE TABLE `upload_part` (
  `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '内部自增主键，不返回浏览器',
  `upload_session_id` BIGINT UNSIGNED NOT NULL COMMENT '上传会话内部ID',
